#!/usr/bin/env bash
# Full performance run on a clean machine (used by .github/workflows/perf.yml):
# start the system with EF Core SQL logging, measure API response times, capture the SQL EF sends,
# then run the database measurements.
set -euo pipefail
cd "$(dirname "$0")/../.."
mkdir -p docs/performance/results

export EF_SQL_LOG_LEVEL=Information
docker compose up -d --build
for i in $(seq 1 60); do curl -fsS http://localhost:5080/health >/dev/null 2>&1 && break; sleep 5; done

{
  echo "# API response times (generated by scripts/perf/api_timings.py)"
  echo
  echo "Machine: GitHub Actions runner ($(nproc) vCPU, $(free -g | awk '/Mem:/{print $2}') GB RAM), SQL Server 2022 Developer and the API in Docker."
  echo
  python3 scripts/perf/api_timings.py 20
} > docs/performance/results/api-timings.md
cat docs/performance/results/api-timings.md

docker compose logs --no-color api | python3 scripts/perf/ef_sql.py > docs/performance/results/ef-sql.log
echo "Captured $(grep -c 'Executed DbCommand' docs/performance/results/ef-sql.log) distinct SQL commands"

python3 scripts/perf/measure.py "$@"
cat docs/performance/results/summary.md
